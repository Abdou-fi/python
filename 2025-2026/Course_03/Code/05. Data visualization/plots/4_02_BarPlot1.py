import matplotlib.pyplot as plt # Import the Matplotlib library
 # Data 
categories = ['A', 'B', 'C', 'D'] # Define categories 
values = [3, 7, 8, 5] # Corresponding values for each category
# Create Bar Plot 
plt.bar(categories, values) # Create a bar plot using categories and values 
plt.title('Bar Plot Example') # Add a title to the plot 
plt.xlabel('Categories') # Label for the X-axis 
plt.ylabel('Values') # Label for the Y-axis 
plt.show() # Display the plot

